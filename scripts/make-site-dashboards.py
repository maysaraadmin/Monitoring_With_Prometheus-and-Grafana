#!/usr/bin/env python3
"""Generate one dedicated Grafana dashboard per monitored website.

    python scripts/make-site-dashboards.py                      # all probed sites
    python scripts/make-site-dashboards.py https://a.com ...    # only these
    docker compose restart grafana

Writes grafana/provisioning/dashboards/site-<slug>.json for every site currently
being probed, and deletes the ones for sites that are no longer probed. Safe to
re-run: it only ever touches files matching site-*.json.

The site list comes from Prometheus, not from sites.yml, for two reasons: there
is no YAML parser in the stdlib, and Prometheus is the authoritative answer to
"what is actually being monitored" -- a typo in sites.yml shows up here as a
missing dashboard rather than as a dashboard full of "no data".

So the stack has to be running. Add your sites to prometheus/targets/sites.yml,
`docker compose restart prometheus`, then run this.

Each generated dashboard is derived from websites.json so the panels stay
identical to the templated one. Edit websites.json to change them all, then
re-run this.
"""
import json
import os
import re
import sys
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DASH_DIR = os.path.join(HERE, 'grafana', 'provisioning', 'dashboards')
TEMPLATE = os.path.join(DASH_DIR, 'websites.json')
PROM = os.environ.get('PROM_URL', 'http://localhost:9090')
PREFIX = 'site-'

# Panels that only make sense on the multi-site board.
DROP_TITLES = {'All sites', 'Every monitored site', '$site'}


def live_sites():
    url = PROM + '/api/v1/query?' + urllib.parse.urlencode({'query': 'probe_success'})
    try:
        with urllib.request.urlopen(url, timeout=20) as r:
            payload = json.load(r)
    except Exception as e:
        sys.exit('cannot reach Prometheus at %s (%s).\n'
                 'Start the stack first: docker compose up -d' % (PROM, e))
    if payload.get('status') != 'success':
        sys.exit('Prometheus returned: %s' % payload.get('error', payload.get('status')))
    sites = sorted({s['metric']['instance'] for s in payload['data']['result']
                    if 'instance' in s['metric']})
    if not sites:
        sys.exit('no sites are being probed. Add URLs to prometheus/targets/sites.yml,\n'
                 'then: docker compose restart prometheus')
    return sites


def slug(site):
    """https://www.foo.com/bar -> www-foo-com-bar . Must be stable: it is the dashboard uid."""
    s = re.sub(r'^[a-z]+://', '', site.strip().rstrip('/'), flags=re.I)
    s = re.sub(r'[^A-Za-z0-9]+', '-', s).strip('-').lower()
    return s or 'site'


def title_of(site):
    host = re.sub(r'^[a-z]+://', '', site.strip().rstrip('/'), flags=re.I)
    return host.split('/')[0]


def substitute(node, site):
    if isinstance(node, dict):
        return {k: substitute(v, site) for k, v in node.items()}
    if isinstance(node, list):
        return [substitute(v, site) for v in node]
    if isinstance(node, str):
        return node.replace('$site', site)
    return node


def build(template, site):
    d = json.loads(json.dumps(template))          # deep copy
    panels = [p for p in d['panels'] if p.get('title') not in DROP_TITLES]
    if not panels:
        sys.exit('template has no per-site panels left after filtering -- check DROP_TITLES')
    top = min(p['gridPos']['y'] for p in panels)
    for p in panels:
        p['gridPos']['y'] -= top                   # close the gap left by the dropped panels
    d['panels'] = substitute(panels, site)
    d['uid'] = slug(site)
    d['title'] = title_of(site)
    d['description'] = (
        'Dedicated dashboard for %s, generated by scripts/make-site-dashboards.py -- '
        'edit websites.json and re-run rather than editing this file. For every site at '
        'once, see the "Website Monitoring" dashboard (uid website-monitoring).' % site)
    d['tags'] = ['blackbox', 'websites', title_of(site)]
    d['templating']['list'] = [v for v in d['templating']['list'] if v['name'] != 'site']
    d['version'] = 1
    # A leftover placeholder would render every panel as "no data", so fail loudly instead.
    assert '$site' not in json.dumps(d['panels']), 'unsubstituted $site in ' + site
    return d


def main():
    with open(TEMPLATE, encoding='utf-8') as fh:
        template = json.load(fh)

    named = sys.argv[1:]
    sites = named or live_sites()
    # Guard: 168 sites x 36 KB would be 5.8 MB of generated JSON and 168 entries in
    # Grafana's list. The templated dashboard already gives each site its own URL, so
    # per-site files are opt-in above a handful. Name the sites you want instead.
    LIMIT = 12
    if len(sites) > LIMIT and len(sys.argv) == 1:
        for line in [
            '%d sites are being probed -- that would generate %d dashboards (~%.1f MB).'
            % (len(sites), len(sites), len(sites) * 36181 / 1048576),
            'The templated "Website Monitoring" dashboard already covers every site at',
            '  /d/website-monitoring/website-monitoring?var-site=<url>',
            'To generate files for specific sites anyway, name them:',
            '  python %s https://a.com https://b.com' % sys.argv[0],
        ]:
            print(line, file=sys.stderr)
        sys.exit(1)
    wanted = {}
    for site in sites:
        wanted[PREFIX + slug(site) + '.json'] = build(template, site)

    collisions = len(sites) - len({slug(s) for s in sites})
    if collisions:
        sys.exit('two sites produce the same slug; give them distinct hostnames')

    for name, dash in sorted(wanted.items()):
        path = os.path.join(DASH_DIR, name)
        before = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        after = json.dumps(dash, indent=2, ensure_ascii=False) + '\n'
        with open(path, 'w', encoding='utf-8', newline='') as fh:
            fh.write(after)
        print('%-8s %-28s uid=%-22s /d/%s/%s' % (
            'updated' if before == after else ('wrote' if before is None else 'changed'),
            name, dash['uid'], dash['uid'], dash['uid']))

    # Prune only when generating for EVERY probed site. With an explicit list the
    # other dashboards were not asked about, and deleting them would be a surprise.
    if named:
        print('\n%d dashboard(s) written. Other site-*.json files left alone.' % len(wanted))
        print('Now: docker compose restart grafana')
        return

    # Only ever remove files this script owns.
    for name in sorted(os.listdir(DASH_DIR)):
        if name.startswith(PREFIX) and name.endswith('.json') and name not in wanted:
            os.remove(os.path.join(DASH_DIR, name))
            print('%-8s %-28s (no longer probed)' % ('removed', name))

    print('\n%d site dashboard(s). Now: docker compose restart grafana' % len(wanted))


if __name__ == '__main__':
    main()
